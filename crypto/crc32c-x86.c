/* One stream of crc32 instructions, for CPUs without PCLMULQDQ */
uint32_t crc32c_x86_sse42(uint32_t crc, unsigned char const *p, uint32_t len)
{
	uint64_t crc64 = crc;
	uint64_t v;

	for (; len >= 8; p += 8, len -= 8) {
		memcpy(&v, p, sizeof(v));
		crc64 = _mm_crc32_u64(crc64, v);
	}
	crc = crc64;
	for (; len; p++, len--)
		crc = _mm_crc32_u8(crc, *p);

	return crc;
}

