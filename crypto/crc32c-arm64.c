/* One stream of crc32c instructions, for CPUs without PMULL */
uint32_t crc32c_armv8(uint32_t crc, unsigned char const *p, uint32_t len)
{
	uint64_t v;

	for (; len >= 8; p += 8, len -= 8) {
		memcpy(&v, p, sizeof(v));
		crc = __crc32cd(crc, v);
	}
	for (; len; p++, len--)
		crc = __crc32cb(crc, *p);

	return crc;
}

